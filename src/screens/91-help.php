function help_pool(bool $admin): array
{
    return $admin ? (HELP_SECTIONS + ADMIN_HELP) : HELP_SECTIONS;
}

function help_matches(string $query, bool $admin): array
{
    $q = trim(mb_strtolower($query));
    $pool = help_pool($admin);
    if ($q === '') {
        return array_slice($pool, 0, 6, true);
    }
    $hits = [];
    foreach ($pool as $key => $item) {
        $score = 0;
        if (str_contains(mb_strtolower($item['title']), $q)) {
            $score = 3;
        } elseif (str_contains(mb_strtolower($item['tags']), $q)) {
            $score = 2;
        } elseif (str_contains(mb_strtolower($item['body']), $q)) {
            $score = 1;
        }
        if ($score) {
            $hits[$key] = $score;
        }
    }
    arsort($hits);
    $result = [];
    foreach ($hits as $key => $score) {
        $result[$key] = $pool[$key];
    }
    return $result;
}

